import { ShieldCheck } from "lucide-react";
import type { AlertRecord } from "../types";

interface AlertTableProps {
  alerts: AlertRecord[];
}

export default function AlertTable({ alerts }: AlertTableProps) {
  return (
    <section className="panel-card min-h-[260px] p-5 sm:p-6">
      <h2 className="text-sm font-semibold text-slate-200">Recent alerts</h2>
      {alerts.length === 0 ? (
        <div className="flex h-[190px] flex-col items-center justify-center">
          <div className="grid h-12 w-12 place-items-center rounded-2xl border border-white/[0.07] bg-white/[0.025] text-slate-600">
            <ShieldCheck size={21} strokeWidth={1.5} />
          </div>
          <p className="mt-4 text-sm font-medium text-slate-400">No alerts available</p>
          <p className="mt-1 max-w-xs text-center text-xs leading-5 text-slate-600">
            Alerts are not generated by this prototype.
          </p>
        </div>
      ) : (
        <div className="mt-5 overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="text-slate-500">
              <tr>
                <th className="pb-3 font-medium">Alert</th>
                <th className="pb-3 font-medium">Severity</th>
                <th className="pb-3 font-medium">Status</th>
                <th className="pb-3 font-medium">Created</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-white/[0.06] text-slate-300">
              {alerts.map((alert) => (
                <tr key={alert.id}>
                  <td className="py-3 pr-3">{alert.title}</td>
                  <td className="py-3 pr-3">{alert.severity}</td>
                  <td className="py-3 pr-3">{alert.status}</td>
                  <td className="py-3">{alert.createdAt}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </section>
  );
}
